#!/bin/bash
set -euo pipefail

# Lays out the extra, symbol-prefixed copies of moonlight-common-c inside a
# checkout of the library: instance1/, instance2/, … next to src/ and enet/.
#
# Each instance directory is a complete SwiftPM C target that compiles the
# *same* sources a second time. It never copies a .c file: every source is a
# two-line shim that defines the instance's symbol prefix, pulls in
# ml_redefine_symbols.h (one `#pragma redefine_extname` per external symbol)
# and then #includes the real file by relative path, so relative includes
# inside the library still resolve against src/ and nanors/. Why a second copy
# is needed at all is explained at the top of ml_redefine_symbols.h.
#
# enet is compiled *into* each instance rather than kept as its own target on
# purpose. Xcode builds SwiftPM C targets with explicit Clang modules, and a
# header that belongs to a module is imported as that module instead of being
# included textually — which would hand the instance enet's unprefixed
# declarations and undo the rename. So the instance gets a private copy of
# enet's headers (enet_include/, without a module map) and compiles enet's
# sources itself.
#
# The instance's one public header is NOT a copy of Limelight.h. If every copy
# declared the same `LiStartConnection` and the same structs, Clang would merge
# them into one entity across the three modules (they are textually identical C
# declarations), Swift would attribute the structs to whichever module loaded
# last, and the renamed functions could resolve to the wrong copy. Instead each
# copy exposes only the entry points the app uses, under its prefixed name, with
# an asm label pointing at the literal symbol `#pragma redefine_extname`
# produced — and every struct pointer as `void *`, so the types stay defined
# once, in MoonlightCommonC. The Swift side (MoonlightLibrarySlotN.swift) hands
# these raw pointers to structs it built with the unprefixed module's types.
#
# Usage: make-instances.sh <moonlight-common-c checkout> [count]
#   count is the number of *extra* copies (default 2, i.e. three sessions in
#   total counting the unprefixed original). Keep it in step with
#   `extraInstances` in Package.swift and `MoonlightLibrary.count` in the app.

REPO="${1:?usage: make-instances.sh <moonlight-common-c checkout> [count]}"
COUNT="${2:-2}"
HERE="$(cd "$(dirname "$0")" && pwd)"

cd "$REPO"
[[ -f src/Limelight.h && -d enet/include/enet ]] || {
    echo "make-instances.sh: $REPO does not look like a moonlight-common-c checkout" >&2
    exit 1
}

for ((n = 1; n <= COUNT; n++)); do
    inst="instance$n"
    prefix="ml${n}_"
    rm -rf "$inst"
    mkdir -p "$inst/include" "$inst/private" "$inst/src" "$inst/enet" "$inst/enet_include"

    # The rename list, private to the instance's own C compile.
    cp "$HERE/ml_redefine_symbols.h" "$inst/private/ml_redefine_symbols.h"

    # The public header Swift imports (see the header comment for its shape).
    # `#pragma redefine_extname` emits the new name as a literal assembler
    # symbol — no leading underscore — so the asm label here is literal too.
    cat > "$inst/include/MoonlightCommonC$n.h" <<HEADER
// Generated by make-instances.sh — do not edit.
// Copy $n of moonlight-common-c: the entry points Longwave uses, prefixed
// with $prefix. See ml_redefine_symbols.h for why copies exist at all, and
// make-instances.sh for why this is not a copy of Limelight.h.
#ifndef MOONLIGHT_COMMON_C_INSTANCE_$n
#define MOONLIGHT_COMMON_C_INSTANCE_$n
#include <stdint.h>
#include <stdbool.h>

#define ML_ENTRY(name) __asm__("$prefix" #name)

int ${prefix}LiStartConnection(void* serverInfo, void* streamConfig, void* clCallbacks,
    void* drCallbacks, void* arCallbacks, void* renderContext, int drFlags,
    void* audioContext, int arFlags) ML_ENTRY(LiStartConnection);
void ${prefix}LiStopConnection(void) ML_ENTRY(LiStopConnection);
void ${prefix}LiInterruptConnection(void) ML_ENTRY(LiInterruptConnection);
const char* ${prefix}LiGetStageName(int stage) ML_ENTRY(LiGetStageName);
bool ${prefix}LiGetEstimatedRttInfo(uint32_t* estimatedRtt, uint32_t* estimatedRttVariance) ML_ENTRY(LiGetEstimatedRttInfo);
bool ${prefix}LiGetHdrMetadata(void* metadata) ML_ENTRY(LiGetHdrMetadata);
void ${prefix}LiRequestIdrFrame(void) ML_ENTRY(LiRequestIdrFrame);
int ${prefix}LiSendMouseMoveEvent(short deltaX, short deltaY) ML_ENTRY(LiSendMouseMoveEvent);
int ${prefix}LiSendMousePositionEvent(short x, short y, short referenceWidth, short referenceHeight) ML_ENTRY(LiSendMousePositionEvent);
int ${prefix}LiSendMouseButtonEvent(char action, int button) ML_ENTRY(LiSendMouseButtonEvent);
int ${prefix}LiSendKeyboardEvent(short keyCode, char keyAction, char modifiers) ML_ENTRY(LiSendKeyboardEvent);
int ${prefix}LiSendHighResScrollEvent(short scrollAmount) ML_ENTRY(LiSendHighResScrollEvent);
int ${prefix}LiSendHighResHScrollEvent(short scrollAmount) ML_ENTRY(LiSendHighResHScrollEvent);
int ${prefix}LiSendMultiControllerEvent(short controllerNumber, short activeGamepadMask,
    int buttonFlags, unsigned char leftTrigger, unsigned char rightTrigger,
    short leftStickX, short leftStickY, short rightStickX, short rightStickY) ML_ENTRY(LiSendMultiControllerEvent);
int ${prefix}LiSendControllerArrivalEvent(uint8_t controllerNumber, uint16_t activeGamepadMask, uint8_t type,
    uint32_t supportedButtonFlags, uint16_t capabilities) ML_ENTRY(LiSendControllerArrivalEvent);

#undef ML_ENTRY
#endif
HEADER

    # enet headers, private to this instance and deliberately without the
    # module map the original enet/include carries (see the header comment).
    cp -R enet/include/enet "$inst/enet_include/enet"
    rm -f "$inst/enet_include/enet/module.modulemap" "$inst/enet_include/module.modulemap"

    shim() { # <shim path> <relative path of the real source>
        cat > "$1" <<SHIM
// Generated by make-instances.sh — do not edit. Compiles $2 as copy $n.
#define ML_INSTANCE_PREFIX $prefix
#include "../private/ml_redefine_symbols.h"
#include "$2"
SHIM
    }
    for f in src/*.c; do
        shim "$inst/src/$(basename "$f")" "../../$f"
    done
    for f in enet/*.c; do
        # win32.c is excluded from the original target too.
        [[ "$(basename "$f")" == "win32.c" ]] && continue
        shim "$inst/enet/$(basename "$f")" "../../$f"
    done
done

echo "make-instances.sh: laid out $COUNT prefixed cop$([[ $COUNT == 1 ]] && echo y || echo ies) in $REPO"
