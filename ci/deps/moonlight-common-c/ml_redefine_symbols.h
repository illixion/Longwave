// Renames every external symbol of moonlight-common-c (plus its bundled enet
// and nanors) so a second and third copy of the library can be linked into one
// binary alongside the first.
//
// moonlight-common-c is written around one connection: its stream
// configuration, callbacks, depacketizer state and worker threads are all
// file-scope or extern globals, and LiStartConnection/LiStopConnection drive
// that single state machine. Nothing in the API takes a handle. The only way to
// stream from two hosts at once is therefore to link the library more than
// once, and static libraries with identical symbol names cannot coexist — so
// each extra copy is compiled from the same sources with every symbol renamed
// behind a prefix (`ml1_`, `ml2_`, …). See make-instances.sh for how the copies
// are laid out and Longwave/Moonlight/MoonlightLibrary.swift for the Swift
// side.
//
// `#pragma redefine_extname` rather than `#define`: it renames the *linker*
// symbol of a declaration without touching the identifier, so it survives the
// macro games rswrapper.c plays with the nanors names (DECORATE_FUNC pastes an
// ISA suffix onto them and then #undefs the bare names), and Swift still sees
// the functions under their documented names — `LiStartConnection` in module
// MoonlightCommonC1 simply binds to `_ml1_LiStartConnection`.
//
// GENERATED from `nm -gjU` over every object of the MoonlightCommonC and enet
// targets, for the ref pinned in scripts/setup-deps.sh, across arm64 and
// x86_64 (the x86 slices add the SSSE3/AVX2/AVX-512 nanors variants). A symbol
// missing here does not fail the link — the archive member that defines it
// first silently wins and one copy starts writing the other's globals — which is
// why scripts/verify-moonlight-instances.sh checks the built objects. Regenerate
// with `scripts/verify-moonlight-instances.sh --regenerate` after bumping the
// dependency ref.
//
// Expects ML_INSTANCE_PREFIX to be defined by the including file.

#ifndef ML_INSTANCE_PREFIX
#error "Define ML_INSTANCE_PREFIX (e.g. ml1_) before including ml_redefine_symbols.h"
#endif

#define ML_CAT_(a, b) a##b
#define ML_CAT(a, b) ML_CAT_(a, b)
#define ML_STR_(s) #s
#define ML_STR(s) ML_STR_(s)
#define ML_RENAME(sym) _Pragma(ML_STR(redefine_extname sym ML_CAT(ML_INSTANCE_PREFIX, sym)))

